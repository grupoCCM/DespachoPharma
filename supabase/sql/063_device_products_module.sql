-- Device / non-pharma products module.
-- Safe rollout: creates separate tables and RPCs; it does not change pharmacy tables.

create extension if not exists pgcrypto;

create table if not exists public.device_products (
  id uuid primary key default gen_random_uuid(),
  external_code integer not null unique,
  name text not null,
  secondary_name text,
  category text,
  brand_code integer,
  brand_name text,
  model text,
  presentation_name text,
  sale_price numeric(14,4),
  default_cost numeric(14,4),
  active boolean not null default true,
  requires_serial boolean not null default true,
  requires_expiration boolean not null default false,
  source_file text,
  source_loaded_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_device_products_active on public.device_products(active);
create index if not exists idx_device_products_name on public.device_products using gin(to_tsvector('spanish', coalesce(name,'') || ' ' || coalesce(secondary_name,'') || ' ' || coalesce(brand_name,'') || ' ' || coalesce(model,'')));

drop trigger if exists trg_device_products_updated_at on public.device_products;
create trigger trg_device_products_updated_at
before update on public.device_products
for each row execute function public.pharma_touch_updated_at();

create table if not exists public.device_units (
  id uuid primary key default gen_random_uuid(),
  device_product_id uuid not null references public.device_products(id),
  serial_code text not null,
  normalized_serial text generated always as (lower(regexp_replace(trim(serial_code), '\s+', '', 'g'))) stored,
  lot_no text,
  expires_at date,
  status text not null default 'available',
  cost numeric(14,4),
  source_doc_no text,
  source_file text,
  registered_by uuid references public.app_users(id),
  registered_at timestamptz not null default now(),
  sold_at timestamptz,
  sold_by uuid references public.app_users(id),
  sale_id uuid,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint device_units_status_check check (status in ('available','sold','inactive','damaged','lost','retired')),
  constraint device_units_serial_not_blank check (length(trim(serial_code)) > 0)
);

create unique index if not exists ux_device_units_normalized_serial on public.device_units(normalized_serial);
create index if not exists idx_device_units_product_status on public.device_units(device_product_id, status);
create index if not exists idx_device_units_expires on public.device_units(expires_at);

drop trigger if exists trg_device_units_updated_at on public.device_units;
create trigger trg_device_units_updated_at
before update on public.device_units
for each row execute function public.pharma_touch_updated_at();

create table if not exists public.device_sales (
  id uuid primary key default gen_random_uuid(),
  sale_no bigint generated by default as identity unique,
  expediente text not null,
  status text not null default 'confirmed',
  created_by uuid references public.app_users(id),
  confirmed_at timestamptz not null default now(),
  note text,
  created_at timestamptz not null default now(),
  constraint device_sales_status_check check (status in ('confirmed','voided'))
);

create index if not exists idx_device_sales_expediente on public.device_sales(expediente);
create index if not exists idx_device_sales_confirmed_at on public.device_sales(confirmed_at);

create table if not exists public.device_sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.device_sales(id) on delete cascade,
  device_unit_id uuid not null references public.device_units(id),
  device_product_id uuid not null references public.device_products(id),
  serial_code text not null,
  product_name_snapshot text not null,
  price numeric(14,4),
  cost numeric(14,4),
  created_at timestamptz not null default now(),
  unique (sale_id, device_unit_id)
);

create index if not exists idx_device_sale_items_product on public.device_sale_items(device_product_id);
create index if not exists idx_device_sale_items_serial on public.device_sale_items(serial_code);
create unique index if not exists ux_device_sale_items_unit on public.device_sale_items(device_unit_id);

