alter table public.device_inventory_movements enable row level security;

create or replace view public.vw_device_inventory_state
with (security_invoker = true) as
select
  p.id as device_product_id,
  p.external_code,
  p.name,
  p.category,
  p.brand_name,
  p.model,
  p.active,
  count(u.id) filter (where u.status = 'available')::integer as available_qty,
  count(u.id) filter (where u.status = 'sold')::integer as sold_qty,
  count(u.id) filter (where u.status in ('inactive','damaged','lost','retired'))::integer as unavailable_qty,
  count(u.id)::integer as physical_units,
  coalesce(sum(u.cost) filter (where u.status = 'available'), 0)::numeric(14,4) as available_cost_value
from public.device_products p
left join public.device_units u on u.device_product_id = p.id
group by p.id, p.external_code, p.name, p.category, p.brand_name, p.model, p.active;

create or replace view public.vw_device_unit_trace
with (security_invoker = true) as
select
  u.id as device_unit_id,
  p.id as device_product_id,
  p.external_code,
  p.name as product_name,
  p.category,
  p.brand_name,
  p.model,
  u.serial_code,
  u.lot_no,
  u.expires_at,
  u.status,
  u.cost,
  u.source_doc_no,
  u.registered_at,
  ru.display_name as registered_by_name,
  u.sold_at,
  su.display_name as sold_by_name,
  s.sale_no,
  s.expediente,
  u.note
from public.device_units u
join public.device_products p on p.id = u.device_product_id
left join public.app_users ru on ru.id = u.registered_by
left join public.app_users su on su.id = u.sold_by
left join public.device_sales s on s.id = u.sale_id;

