create table if not exists public.device_inventory_movements (
  id uuid primary key default gen_random_uuid(),
  device_unit_id uuid references public.device_units(id),
  device_product_id uuid not null references public.device_products(id),
  serial_code text,
  movement_type text not null,
  qty_delta integer not null,
  source_type text,
  source_id uuid,
  source_event_key text,
  note text,
  created_by uuid references public.app_users(id),
  created_at timestamptz not null default now(),
  constraint device_inventory_movements_qty_check check (qty_delta <> 0),
  constraint device_inventory_movements_type_check check (movement_type in ('receive','sale','sale_void','admin_adjustment'))
);

create unique index if not exists ux_device_inventory_movements_source_event_key
on public.device_inventory_movements(source_event_key)
where source_event_key is not null;

create index if not exists idx_device_inventory_movements_product_created
on public.device_inventory_movements(device_product_id, created_at);

alter table public.device_products enable row level security;
alter table public.device_units enable row level security;
alter table public.device_sales enable row level security;
