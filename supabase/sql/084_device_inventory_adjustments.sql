-- Explicit, auditable inventory adjustments for serialized devices.
-- Existing unit, sale and movement history is preserved unchanged.

create table if not exists public.device_inventory_adjustments (
  id uuid primary key default gen_random_uuid(),
  adjustment_no bigint generated by default as identity unique,
  request_id uuid not null unique,
  device_unit_id uuid not null references public.device_units(id),
  action text not null,
  from_product_id uuid not null references public.device_products(id),
  to_product_id uuid not null references public.device_products(id),
  from_status text not null,
  to_status text not null,
  qty_delta integer not null default 0,
  reason_code text not null,
  reason_detail text not null,
  reference_no text,
  old_data jsonb not null,
  new_data jsonb not null,
  created_by uuid not null references public.app_users(id),
  created_at timestamptz not null default now(),
  constraint device_inventory_adjustments_action_check
    check (action in ('correction','retire','reinstate','reclassify')),
  constraint device_inventory_adjustments_qty_check
    check (qty_delta in (-1,0,1)),
  constraint device_inventory_adjustments_reason_code_check
    check (reason_code in ('entry_error','damage','loss','found','repaired','return','other')),
  constraint device_inventory_adjustments_reason_detail_check
    check (length(trim(reason_detail)) >= 3)
);

create index if not exists idx_device_inventory_adjustments_unit_created
on public.device_inventory_adjustments(device_unit_id, created_at desc);

create index if not exists idx_device_inventory_adjustments_created
on public.device_inventory_adjustments(created_at desc);

alter table public.device_inventory_adjustments enable row level security;

create or replace function public.rpc_device_inventory_adjustment_apply(
  p_session_token text,
  p_request_id uuid,
  p_device_unit_id uuid,
  p_action text,
  p_reason_code text,
  p_reason_detail text,
  p_reference_no text default null,
  p_target_external_code integer default null,
  p_target_status text default null,
  p_lot_no text default null,
  p_expires_at date default null,
  p_cost numeric default null,
  p_source_doc_no text default null,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid;
  v_role public.user_role;
  v_old public.device_units%rowtype;
  v_target public.device_products%rowtype;
  v_action text := lower(trim(coalesce(p_action,'')));
  v_reason_code text := lower(trim(coalesce(p_reason_code,'')));
  v_reason_detail text := nullif(trim(coalesce(p_reason_detail,'')), '');
  v_reference_no text := nullif(trim(coalesce(p_reference_no,'')), '');
  v_target_status text := lower(trim(coalesce(p_target_status,'')));
  v_adjustment_id uuid;
  v_adjustment_no bigint;
  v_qty_delta integer := 0;
  v_existing public.device_inventory_adjustments%rowtype;
  v_new_data jsonb;
begin
  select user_id, role into v_user_id, v_role
  from public.app_require_session(p_session_token);

  if v_role <> 'admin' then
    raise exception 'Solo administrador puede aplicar ajustes de inventario de dispositivos';
  end if;

  if p_request_id is null then
    raise exception 'Identificador de solicitud requerido';
  end if;

  select * into v_existing
  from public.device_inventory_adjustments
  where request_id = p_request_id;

  if v_existing.id is not null then
    return jsonb_build_object(
      'status', 'already_applied',
      'adjustment_id', v_existing.id,
      'adjustment_no', v_existing.adjustment_no,
      'device_unit_id', v_existing.device_unit_id,
      'action', v_existing.action,
      'qty_delta', v_existing.qty_delta
    );
  end if;

  if v_action not in ('correction','retire','reinstate','reclassify') then
    raise exception 'Tipo de ajuste no permitido';
  end if;

  if v_reason_code not in ('entry_error','damage','loss','found','repaired','return','other') then
    raise exception 'Motivo de ajuste no permitido';
  end if;

  if v_reason_detail is null or length(v_reason_detail) < 3 then
    raise exception 'Describe el motivo del ajuste';
  end if;

  select * into v_old
  from public.device_units
  where id = p_device_unit_id
  for update;

  if v_old.id is null then
    raise exception 'Unidad no encontrada';
  end if;

  -- A concurrent retry waits for the unit lock, then returns the committed result.
  select * into v_existing
  from public.device_inventory_adjustments
  where request_id = p_request_id;

  if v_existing.id is not null then
    return jsonb_build_object(
      'status', 'already_applied',
      'adjustment_id', v_existing.id,
      'adjustment_no', v_existing.adjustment_no,
      'device_unit_id', v_existing.device_unit_id,
      'action', v_existing.action,
      'qty_delta', v_existing.qty_delta
    );
  end if;

  if v_old.status = 'sold' or v_old.sale_id is not null then
    raise exception 'Una unidad entregada se corrige mediante anulacion de la entrega, no por ajuste administrativo';
  end if;

  select * into v_target
  from public.device_products
  where id = v_old.device_product_id;

  if v_action = 'correction' then
    update public.device_units
    set lot_no = nullif(trim(coalesce(p_lot_no,'')), ''),
        expires_at = p_expires_at,
        cost = p_cost,
        source_doc_no = nullif(trim(coalesce(p_source_doc_no,'')), ''),
        note = nullif(trim(coalesce(p_note,'')), '')
    where id = v_old.id;

  elsif v_action = 'retire' then
    if v_old.status <> 'available' then
      raise exception 'Solo una unidad disponible puede retirarse. Estado actual: %', v_old.status;
    end if;
    if v_target_status not in ('inactive','damaged','lost','retired') then
      raise exception 'Selecciona un estado de retiro valido';
    end if;
    v_qty_delta := -1;
    update public.device_units
    set status = v_target_status,
        note = concat_ws(' | ', note, 'Ajuste: ' || v_reason_detail)
    where id = v_old.id;

  elsif v_action = 'reinstate' then
    if v_old.status not in ('inactive','damaged','lost','retired') then
      raise exception 'Solo una unidad no disponible puede reintegrarse. Estado actual: %', v_old.status;
    end if;
    if not coalesce(v_target.active, false) then
      raise exception 'No se puede reintegrar una unidad de un producto inactivo';
    end if;
    if v_old.expires_at is not null and v_old.expires_at <= current_date then
      raise exception 'No se puede reintegrar una unidad vencida';
    end if;
    v_qty_delta := 1;
    update public.device_units
    set status = 'available',
        note = concat_ws(' | ', note, 'Reintegro: ' || v_reason_detail)
    where id = v_old.id;

  else
    if v_old.status <> 'available' then
      raise exception 'Solo una unidad disponible puede reclasificarse. Estado actual: %', v_old.status;
    end if;
    select * into v_target
    from public.device_products
    where external_code = p_target_external_code
      and active = true;
    if v_target.id is null then
      raise exception 'Producto destino no activo o no existe';
    end if;
    if v_target.id = v_old.device_product_id then
      raise exception 'El producto destino debe ser diferente al producto actual';
    end if;
    update public.device_units
    set device_product_id = v_target.id,
        note = concat_ws(' | ', note, 'Reclasificado: ' || v_reason_detail)
    where id = v_old.id;
  end if;

  select to_jsonb(u) into v_new_data
  from public.device_units u
  where u.id = v_old.id;

  insert into public.device_inventory_adjustments(
    request_id, device_unit_id, action, from_product_id, to_product_id,
    from_status, to_status, qty_delta, reason_code, reason_detail,
    reference_no, old_data, new_data, created_by
  ) values (
    p_request_id, v_old.id, v_action, v_old.device_product_id, v_target.id,
    v_old.status, coalesce(v_new_data->>'status', v_old.status), v_qty_delta,
    v_reason_code, v_reason_detail, v_reference_no, to_jsonb(v_old), v_new_data, v_user_id
  )
  returning id, adjustment_no into v_adjustment_id, v_adjustment_no;

  if v_action = 'retire' then
    insert into public.device_inventory_movements(
      device_unit_id, device_product_id, serial_code, movement_type, qty_delta,
      source_type, source_id, source_event_key, note, created_by
    ) values (
      v_old.id, v_old.device_product_id, v_old.serial_code, 'admin_adjustment', -1,
      'device_inventory_adjustment', v_adjustment_id, 'device_adjustment:' || v_adjustment_id::text || ':out',
      concat('Retiro #', v_adjustment_no, ': ', v_reason_detail), v_user_id
    );
  elsif v_action = 'reinstate' then
    insert into public.device_inventory_movements(
      device_unit_id, device_product_id, serial_code, movement_type, qty_delta,
      source_type, source_id, source_event_key, note, created_by
    ) values (
      v_old.id, v_old.device_product_id, v_old.serial_code, 'admin_adjustment', 1,
      'device_inventory_adjustment', v_adjustment_id, 'device_adjustment:' || v_adjustment_id::text || ':in',
      concat('Reintegro #', v_adjustment_no, ': ', v_reason_detail), v_user_id
    );
  elsif v_action = 'reclassify' then
    insert into public.device_inventory_movements(
      device_unit_id, device_product_id, serial_code, movement_type, qty_delta,
      source_type, source_id, source_event_key, note, created_by
    ) values
    (
      v_old.id, v_old.device_product_id, v_old.serial_code, 'admin_adjustment', -1,
      'device_inventory_adjustment', v_adjustment_id, 'device_adjustment:' || v_adjustment_id::text || ':from',
      concat('Reclasificacion #', v_adjustment_no, ' hacia ', v_target.external_code, ': ', v_reason_detail), v_user_id
    ),
    (
      v_old.id, v_target.id, v_old.serial_code, 'admin_adjustment', 1,
      'device_inventory_adjustment', v_adjustment_id, 'device_adjustment:' || v_adjustment_id::text || ':to',
      concat('Reclasificacion #', v_adjustment_no, ' desde ', (select external_code from public.device_products where id = v_old.device_product_id), ': ', v_reason_detail), v_user_id
    );
  end if;

  return jsonb_build_object(
    'status', 'applied',
    'adjustment_id', v_adjustment_id,
    'adjustment_no', v_adjustment_no,
    'device_unit_id', v_old.id,
    'action', v_action,
    'qty_delta', v_qty_delta
  );
end;
$$;

create or replace function public.rpc_device_inventory_adjustment_list(
  p_session_token text,
  p_query text default '',
  p_limit integer default 30
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_role public.user_role;
  v_query text := lower(trim(coalesce(p_query,'')));
  v_limit integer := greatest(1, least(coalesce(p_limit,30), 100));
begin
  select role into v_role
  from public.app_require_session(p_session_token);
  if v_role <> 'admin' then
    raise exception 'Solo administrador puede consultar ajustes de dispositivos';
  end if;

  return coalesce((
    select jsonb_agg(to_jsonb(x) order by x.created_at desc, x.adjustment_no desc)
    from (
      select
        a.id as adjustment_id,
        a.adjustment_no,
        a.action,
        a.qty_delta,
        a.from_status,
        a.to_status,
        a.reason_code,
        a.reason_detail,
        a.reference_no,
        a.created_at,
        u.serial_code,
        fp.external_code as from_external_code,
        fp.name as from_product_name,
        tp.external_code as to_external_code,
        tp.name as to_product_name,
        au.display_name as user_name
      from public.device_inventory_adjustments a
      join public.device_units u on u.id = a.device_unit_id
      join public.device_products fp on fp.id = a.from_product_id
      join public.device_products tp on tp.id = a.to_product_id
      left join public.app_users au on au.id = a.created_by
      where v_query = ''
         or lower(u.serial_code) like '%' || v_query || '%'
         or lower(fp.name) like '%' || v_query || '%'
         or lower(tp.name) like '%' || v_query || '%'
         or a.adjustment_no::text = v_query
         or lower(coalesce(a.reference_no,'')) like '%' || v_query || '%'
      order by a.created_at desc, a.adjustment_no desc
      limit v_limit
    ) x
  ), '[]'::jsonb);
end;
$$;

revoke all on function public.rpc_device_inventory_adjustment_apply(text, uuid, uuid, text, text, text, text, integer, text, text, date, numeric, text, text) from public;
revoke all on function public.rpc_device_inventory_adjustment_list(text, text, integer) from public;
grant execute on function public.rpc_device_inventory_adjustment_apply(text, uuid, uuid, text, text, text, text, integer, text, text, date, numeric, text, text) to anon, authenticated;
grant execute on function public.rpc_device_inventory_adjustment_list(text, text, integer) to anon, authenticated;

comment on table public.device_inventory_adjustments is
  'Immutable audit header for administrative adjustments to serialized device inventory.';
comment on function public.rpc_device_inventory_adjustment_apply(text, uuid, uuid, text, text, text, text, integer, text, text, date, numeric, text, text) is
  'Atomically corrects, retires, reinstates or reclassifies one unsold serialized device unit.';

notify pgrst, 'reload schema';
